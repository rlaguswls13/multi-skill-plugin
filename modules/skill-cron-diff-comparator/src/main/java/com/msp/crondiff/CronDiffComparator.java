package com.msp.crondiff;

import java.time.LocalDateTime;
import java.util.*;

/**
 * Comparator analyzing overlap, differences, and schedule collisions between two Cron expressions.
 */
public final class CronDiffComparator {

    private CronDiffComparator() {
    }

    /**
     * Compares two 5-field cron expressions over a specific time window [start, end].
     *
     * @param cronA first cron expression (e.g. "0 9 * * 1-5")
     * @param cronB second cron expression (e.g. "0 9-18 * * 1-5")
     * @param start start timestamp (inclusive)
     * @param end   end timestamp (inclusive)
     * @return comparison result with common and unique timestamps
     */
    public static CronDiffResult compare(String cronA, String cronB, LocalDateTime start, LocalDateTime end) {
        Objects.requireNonNull(cronA, "cronA must not be null");
        Objects.requireNonNull(cronB, "cronB must not be null");
        Objects.requireNonNull(start, "start time must not be null");
        Objects.requireNonNull(end, "end time must not be null");

        if (end.isBefore(start)) {
            throw new IllegalArgumentException("end time cannot be before start time");
        }

        CronExpression expA = CronExpression.parse(cronA);
        CronExpression expB = CronExpression.parse(cronB);

        List<LocalDateTime> bothMatch = new ArrayList<>();
        List<LocalDateTime> onlyA = new ArrayList<>();
        List<LocalDateTime> onlyB = new ArrayList<>();

        LocalDateTime cur = start.withSecond(0).withNano(0);
        LocalDateTime limit = end.withSecond(0).withNano(0);

        while (!cur.isAfter(limit)) {
            boolean matchA = expA.matches(cur);
            boolean matchB = expB.matches(cur);

            if (matchA && matchB) {
                bothMatch.add(cur);
            } else if (matchA) {
                onlyA.add(cur);
            } else if (matchB) {
                onlyB.add(cur);
            }

            cur = cur.plusMinutes(1);
        }

        return new CronDiffResult(cronA, cronB, bothMatch, onlyA, onlyB);
    }

    /**
     * Compares the next N combined unique occurrences generated by Cron A or Cron B starting from reference time.
     *
     * @param cronA          first cron expression
     * @param cronB          second cron expression
     * @param start          start timestamp (inclusive)
     * @param maxOccurrences maximum number of unique scheduled events to simulate
     * @return comparison result
     */
    public static CronDiffResult compareNextOccurrences(String cronA, String cronB, LocalDateTime start, int maxOccurrences) {
        Objects.requireNonNull(cronA, "cronA must not be null");
        Objects.requireNonNull(cronB, "cronB must not be null");
        Objects.requireNonNull(start, "start time must not be null");

        if (maxOccurrences <= 0) {
            throw new IllegalArgumentException("maxOccurrences must be greater than 0: " + maxOccurrences);
        }

        CronExpression expA = CronExpression.parse(cronA);
        CronExpression expB = CronExpression.parse(cronB);

        List<LocalDateTime> bothMatch = new ArrayList<>();
        List<LocalDateTime> onlyA = new ArrayList<>();
        List<LocalDateTime> onlyB = new ArrayList<>();

        LocalDateTime cur = start.withSecond(0).withNano(0);
        int collectedCount = 0;
        int maxMinutesSafetyLimit = 525600 * 5; // 5 years in minutes
        int minutesChecked = 0;

        while (collectedCount < maxOccurrences && minutesChecked < maxMinutesSafetyLimit) {
            boolean matchA = expA.matches(cur);
            boolean matchB = expB.matches(cur);

            if (matchA || matchB) {
                if (matchA && matchB) {
                    bothMatch.add(cur);
                } else if (matchA) {
                    onlyA.add(cur);
                } else {
                    onlyB.add(cur);
                }
                collectedCount++;
            }

            cur = cur.plusMinutes(1);
            minutesChecked++;
        }

        return new CronDiffResult(cronA, cronB, bothMatch, onlyA, onlyB);
    }
}
